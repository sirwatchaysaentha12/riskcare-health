// ข้อจำกัด: เป็นการคัดกรองเบื้องต้น ไม่ใช่การวินิจฉัยโรค หากมีอาการควรพบแพทย์

export const RISK_QUESTIONS = [
  { id: 'chronic_cough', label: 'ไอเรื้อรังนานเกิน 8 สัปดาห์' },
  { id: 'dyspnea', label: 'หายใจเหนื่อย/หอบผิดปกติเมื่อทำกิจกรรม' },
  { id: 'smoking', label: 'สูบบุหรี่ หรืออยู่ใกล้ผู้สูบบุหรี่เป็นประจำ' },
  { id: 'chronic_disease', label: 'มีโรคหืด โรคปอดอุดกั้นเรื้อรัง หรือโรคหัวใจ' },
  { id: 'age_risk', label: 'อายุ 65 ปีขึ้นไป หรือมีเด็กเล็กในครอบครัว' },
  { id: 'pm_exposure', label: 'อยู่ในพื้นที่ที่ค่าฝุ่น PM2.5 เกินเกณฑ์เป็นประจำ' },
]

// คะแนน = จำนวนข้อที่ตอบใช่ — 0 = ต่ำ, 1–2 = ปานกลาง, 3+ = สูง
// (เกณฑ์เชิงประจักษ์ของโปรเจกต์ ใช้คัดกรองเชิงสาธิตเท่านั้น)
export function computeRiskLevel(answers) {
  const checked = RISK_QUESTIONS.filter((question) => answers?.[question.id]).map((question) => question.id)
  const count = checked.length
  if (count >= 3) {
    return {
      level: 'สูง',
      score: count,
      checked,
      advice: 'มีหลายปัจจัยเสี่ยงร่วมกัน ควรลดกิจกรรมกลางแจ้งช่วงฝุ่นสูง เตรียมยา/อุปกรณ์ตามคำแนะนำแพทย์ และพิจารณาพบแพทย์เพื่อตรวจสุขภาพปอด',
    }
  }
  if (count >= 1) {
    return {
      level: 'ปานกลาง',
      score: count,
      checked,
      advice: 'มีปัจจัยเสี่ยงบางส่วน ควรเฝ้าระวังอาการช่วงฝุ่นสูง สวมหน้ากากป้องกัน PM2.5 และติดตามค่าฝุ่นรายวัน',
    }
  }
  return {
    level: 'ต่ำ',
    score: 0,
    checked: [],
    advice: 'ไม่พบปัจจัยเสี่ยงจากแบบประเมิน ควรดูแลสุขภาพทางเดินหายใจต่อเนื่องและติดตามค่าฝุ่นในพื้นที่',
  }
}
